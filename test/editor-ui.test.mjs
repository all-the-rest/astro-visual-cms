import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { Script } from 'node:vm'
import test from 'node:test'

const UI_PATH = new URL('../src/editor/index.html', import.meta.url)

test('editor client previews and confirms source changes with trusted routes and real viewport presets', async () => {
  const html = await readFile(UI_PATH, 'utf8')
  const script = html.match(/<script nonce="__CSP_NONCE__">([\s\S]*?)<\/script>/)?.[1]
  assert.ok(script, 'The editor must include its browser client.')
  assert.doesNotThrow(() => new Script(script))
  assert.match(script, /addEventListener\('dragstart'/)
  assert.match(script, /addEventListener\('dragover'/)
  assert.match(script, /addEventListener\('drop'/)
  assert.match(script, /await prepareOrder\(galleryId, nextOrder\)/)
  assert.match(script, /aria-label/)
  assert.match(script, /aria-pressed/)
  assert.match(script, /selectedGalleryId/)
  assert.match(script, /galleryById\(galleryId\)/)
  assert.match(script, /'x-editor-token': editorToken/)
  assert.match(script, /async function refreshSession\(\)/)
  assert.match(script, /apiFetch\('\/api\/session'/)
  assert.match(script, /error\.status === 403/)
  assert.match(script, /async function loadWithRetry\(\)/)
  assert.match(script, /const loadPanelState = async \(endpoint, label, fallback\)/)
  assert.match(script, /Andere konfigurierte Bereiche bleiben verfügbar/)
  assert.match(script, /STATE_RETRY_DELAY_MS = 2000/)
  assert.match(script, /Neuer Versuch in 2 Sekunden/)
  assert.match(script, /button\.disabled = busy\(\)/)
  assert.match(script, /postOperation\('\/api\/preview'/)
  assert.match(script, /postOperation\('\/api\/commit'/)
  assert.match(script, /previewId: operation\.previewId/)
  assert.match(script, /diffBefore\.textContent = pendingPreview\.diff\.before/)
  assert.match(script, /diffAfter\.textContent = pendingPreview\.diff\.after/)
  assert.match(script, /api\/preview-ready\?hash=/)
  assert.match(script, /alle Galerien/)
  assert.doesNotMatch(script, /\/api\/reorder/)
  assert.match(script, /configuredPreviewRoutes/)
  assert.match(script, /cacheBustOnRevision/)
  // A local API call that never answers must not leave the editor permanently busy;
  // every request goes through the bounded helper (issue #25).
  assert.match(script, /const API_REQUEST_TIMEOUT_MS = 10000/)
  assert.match(script, /async function apiFetch\(url, options = \{\}\)/)
  assert.match(script, /controller\.abort\(\)/)
  assert.match(script, /Zeitüberschreitung: \$\{method\} \$\{url\}/)
  assert.match(script, /hat nach \$\{seconds\} Sekunden/)
  assert.match(script, /timeout: true/)
  assert.equal((script.match(/\bfetch\(/g) || []).length, 1, 'only the bounded helper may call fetch directly')
  assert.match(script, /button\.textContent = route\.label/)
  const previewNavigation = script.slice(script.indexOf('function navigatePreview'), script.indexOf("previewNavigation.addEventListener('click'"))
  assert.match(previewNavigation, /currentUrl\.searchParams\.delete\('draftReset'\)/)
  assert.match(previewNavigation, /const reload = force \|\| !currentUrl \|\| currentUrl\.href !== requestedUrl\.href/)
  assert.match(previewNavigation, /if \(reload\) preview\.src = url/)
  assert.match(script, /preview\.width = Number\(button\.dataset\.width\)/)
  assert.match(script, /preview\.height = Number\(button\.dataset\.height\)/)
  assert.match(html, /data-preview-preset="desktop" data-width="1280" data-height="800"/)
  assert.match(html, /data-preview-preset="tablet" data-width="768" data-height="1024"/)
  assert.match(html, /data-preview-preset="mobile" data-width="390" data-height="844"/)
  assert.match(html, /__SITE_BASE_PATH__src\/styles\/global\.css/)
  assert.match(html, /<link rel="stylesheet" href="\/editor\.css"/)
  assert.match(html, /id="collections-panel"[^>]*hidden/)
  assert.match(script, /loadPanelState\('\/api\/collections', 'Sammlungen'/)
  assert.match(script, /unavailablePanels\.has\('Sammlungen'\)/)
  assert.match(script, /unavailablePanels\.add\(label\)/)
  assert.doesNotMatch(script, /startsWith\('Collections \('\)/)
  assert.match(script, /function withoutTerminalPunctuation/)
  assert.match(script, /withoutTerminalPunctuation\(error\.message\)/)
  assert.match(script, /Sammlungen konnten nicht neu geladen werden/)
  assert.match(script, /postOperation\('\/api\/collections\/preview'/)
  assert.match(script, /postOperation\('\/api\/collections\/commit'/)
  assert.match(script, /collectionDiffBefore\.textContent = pendingCollectionPreview\.diff\.before/)
  assert.match(script, /collectionDiffAfter\.textContent = pendingCollectionPreview\.diff\.after/)
  assert.match(script, /collectionState\.reason \|\| collectionState\.configEditing\?\.reason/)
  assert.match(script, /GERMAN_REASON_TRANSLATIONS/)
  assert.match(script, /Nicht übersetzte Ursache/)
  assert.match(script, /germanReason\(result\.error\)/)
  assert.match(script, /germanReason\(collection\.creationReason\)/)
  assert.match(script, /function syncGalleryAvailability/)
  assert.match(script, /function galleryLoadMessage/)
  assert.match(script, /syncGalleryAvailability\(\)/)
  assert.match(script, /Keine unterstützte Galerie zur Bearbeitung konfiguriert/)
  assert.match(html, /id="mdx-components-panel"[^>]*hidden/)
  assert.match(script, /loadPanelState\('\/api\/mdx-components', 'MDX-Komponenten'/)
  assert.match(script, /postOperation\('\/api\/mdx-components\/preview'/)
  assert.match(script, /postOperation\('\/api\/mdx-components\/commit'/)
  assert.match(script, /Object\.keys\(instance\?\.props \|\| \{\}\)/)
  assert.match(script, /mdxReason\.textContent = target\?\.error/)
  assert.match(script, /const draft = mdxDrafts\.has\(key\) \? mdxDrafts\.get\(key\) : instance\.props\[mdxProp\.value\]/)
  assert.match(script, /pendingMdxPreview\.diff\.before/)
  assert.match(script, /pendingMdxPreview\.diff\.after/)
  assert.match(html, /id="mdx-blocks-panel"[^>]*hidden/)
  assert.match(script, /loadPanelState\('\/api\/mdx-blocks', 'MDX-Blöcke'/)
  assert.match(script, /postOperation\('\/api\/mdx-blocks\/preview'/)
  assert.match(script, /postOperation\('\/api\/mdx-blocks\/commit'/)
  assert.match(script, /avcms:mdx-block-preview/)
  assert.match(script, /avcms:mdx-block-reset/)
  assert.match(script, /const MDX_BLOCK_RENDER_WAIT_MS = 8000;/)
  assert.match(script, /const MDX_BLOCK_RENDER_ACK_TIMEOUT_MS = 5000;/)
  assert.match(script, /const MDX_BLOCK_PREVIEW_TIMEOUT_MS = 20000;/)
  assert.match(script, /async function renewExpiredMdxBlockPreview\(expired\)/)
  const confirmStart = script.indexOf("document.querySelector('#mdx-block-confirm').addEventListener")
  const confirmEnd = script.indexOf('const resetMdxSelectionReadOnly')
  assert.ok(confirmStart >= 0 && confirmEnd > confirmStart, 'the block confirmation handler must stay addressable')
  const blockConfirmation = script.slice(confirmStart, confirmEnd)
  assert.match(blockConfirmation, /error\.status === 409/)
  assert.match(blockConfirmation, /error\.code !== 'SOURCE_REPLACEMENT_DISABLED'/)
  assert.match(blockConfirmation, /await renewExpiredMdxBlockPreview\(confirmed\)/)
  assert.match(blockConfirmation, /mdxBlockDrafts\.delete\(confirmed\.targetId\)/, 'an unconfirmable draft must be discarded visibly')
  assert.match(blockConfirmation, /await resetMdxBlockOverlay\(target\)/, 'discarding must restore the saved source in the preview')
  assert.match(script, /action: 'move'/)
  assert.match(script, /action: 'remove'/)
  assert.match(script, /kind: 'mdx-blocks'/)
  assert.match(script, /sourceFormat === 'md'/)
  assert.match(script, /sourceFormat: result\.sourceFormat \|\| target\.sourceFormat/)
  assert.match(script, /application: sourceFormat === 'md'/)
  assert.match(script, /mode: 'literal-markdown'/)
  assert.match(script, /CONTENT_LAYER_UNSUPPORTED/)
  assert.match(script, /PREVIEW_NOT_OVERLAID/)
  assert.match(script, /Content-Layer-Eintrag/)
  assert.match(script, /nicht geladen/)
  assert.match(html, /Block einfügen und Astro-Vorschau aktualisieren/)
  assert.match(html, /Änderungen in Vorschau übernehmen/)
  assert.match(html, /Entwurf verwerfen/)
  assert.match(html, /id="markdown-draft-panel"[^>]*hidden/)
  assert.match(html, /id="markdown-draft-apply"/)
  assert.match(script, /postOperation\('\/api\/markdown-drafts\/preview'/)
  assert.match(script, /await updateMarkdownDraftInPreview\(selected, operation\.value, selected\.renderedText\)/)
  assert.match(script, /preview\.contentWindow\.postMessage\(/)
  assert.doesNotMatch(script, /preview\.contentDocument/)
  assert.match(script, /avcms:draft-selection/)
  assert.match(script, /const discardedDraft = Boolean\(selectedMarkdownDraft\)/)
  assert.match(script, /previewFrameUrl = ''/)
  const draftStart = script.indexOf('function updateMarkdownDraftInPreview')
  const draftEnd = script.indexOf('function galleryById')
  assert.ok(draftStart >= 0 && draftEnd > draftStart)
  const markdownDraftUi = script.slice(draftStart, draftEnd)
  assert.doesNotMatch(markdownDraftUi, /sourceProposal|\/api\/mdx-components\/(?:preview|commit)|\/api\/commit/)
  assert.match(script, /window\.setInterval\(pollMdxRevision, 2000\)/)
  assert.match(script, /window\.addEventListener\('focus', pollMdxRevision\)/)
  assert.match(script, /mdxDraftConflict/)
  assert.match(html, /Verwerfen und neu laden/)
  assert.match(html, /Eingabe erneut anwenden und Diff erstellen/)
  assert.match(script, /await prepareMdxChange\(\)/)
  assert.match(html, /role="alert" aria-live="assertive"/)
  assert.match(script, /MDX-Änderung abgebrochen/)
  assert.doesNotMatch(script, /innerHTML|outerHTML/)
  assert.match(html, /id="create-collection-form"/)
  assert.match(html, /id="extend-field-form"/)
  assert.match(script, /creationSupported/)
  assert.match(script, /fieldExtensionSupported/)
  assert.match(script, /prepareConfig\('\/api\/collections\/config\/create\/preview'/)
  assert.match(script, /prepareConfig\('\/api\/collections\/config\/preview'/)
  assert.match(script, /config\/create\/commit/)
  assert.match(script, /config\/cancel/)
  assert.match(script, /collectionState\.configHash/)
  assert.match(script, /if \(!response\.ok\) throw new Error\(germanReason\(result\.error\) \|\| `Status \$\{response\.status\}`\)/)
  assert.match(script, /Abbruch nicht bestätigt/)
})
